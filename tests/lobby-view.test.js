assert(L.html(view({players:two.slice(0,1)})).includes('class="lobby-tap"'),'removing a player restores the wristband prompt');
html=L.html(view({players:two,selection:{mode:'tnt',variant:null,difficulty:'hard',durationMinutes:null}}));
